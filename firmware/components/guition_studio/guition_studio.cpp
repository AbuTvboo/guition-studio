  const char *x = icon_symbol("close");
  lv_obj_center(make_label(close, icon_font(28), 0xE6EDF3, x ? x : "X"));

  // colour swatches: 6 columns x 3 rows
  int cols = 6, size = 62, gap = 12, x0 = (SCREEN_W - cols * size - (cols - 1) * gap) / 2, y0 = 72;
