void GuitionStudio::build_tile_(int page_index, lv_obj_t *parent, const TileCfg &t) {
  const auto &page = this->layout_.pages[page_index];
  int area_w = SCREEN_W - 2 * MARGIN;
  int area_h = this->page_h_ - 2 * MARGIN;
  int cw = (area_w - (page.cols - 1) * GAP) / page.cols;
  int ch = (area_h - (page.rows - 1) * GAP) / page.rows;
  int px = MARGIN + t.x * (cw + GAP);
  int py = MARGIN + t.y * (ch + GAP);
  int pw = t.w * cw + (t.w - 1) * GAP;
  int ph = t.h * ch + (t.h - 1) * GAP;

  TileView view;
  view.page = page_index;
  view.cfg = &t;
  lv_obj_t *o = make_plain(parent);
  view.obj = o;
  lv_obj_set_pos(o, px, py);
  lv_obj_set_size(o, pw, ph);
  lv_obj_set_style_radius(o, t.radius, 0);
  lv_obj_set_style_bg_opa(o, LV_OPA_COVER, 0);
  lv_obj_set_style_bg_color(o, lv_color_hex(t.bg), 0);
  lv_obj_set_style_border_width(o, t.border, 0);
  lv_obj_set_style_border_color(o, lv_color_hex(t.border_color), 0);
  lv_obj_set_style_border_opa(o, LV_OPA_COVER, 0);
  lv_obj_set_style_opa(o, static_cast<lv_opa_t>(t.opacity * 255 / 100), 0);
  lv_obj_set_style_clip_corner(o, true, 0);

  int index = static_cast<int>(this->views_.size());
  lv_obj_set_user_data(o, reinterpret_cast<void *>(static_cast<intptr_t>(index)));
  lv_obj_add_flag(o, LV_OBJ_FLAG_CLICKABLE);
  lv_obj_add_event_cb(o, tile_event_cb, LV_EVENT_ALL, this);

  bool big = (pw >= 200 && ph >= 200);
  int pad = ph < 90 ? 8 : 12;
  const char *sym = icon_symbol(t.icon);
  const lv_font_t *title_font = font_step(t.font);
  int inner_w = pw - 2 * pad;
  bool with_icon = sym != nullptr && t.show_icon;

  auto title_label = [&](lv_align_t align, int x, int y, int width) {
    view.title = make_label(o, title_font, t.fg, t.title.c_str());
    lv_obj_set_width(view.title, width);
    lv_label_set_long_mode(view.title, LABEL_LONG_DOTS);
    lv_obj_align(view.title, align, x, y);
  };

  if (t.kind == "clock") {
    view.value = make_label(o, font_px(big ? 40 : 28), t.fg, "--:--");
    lv_obj_align(view.value, LV_ALIGN_CENTER, 0, t.show_title ? -10 : 0);
    if (t.show_title) {
      view.sub = make_label(o, font_px(16), t.fg, "");
      lv_obj_align(view.sub, LV_ALIGN_CENTER, 0, big ? 32 : 24);
    }
  } else if (t.kind == "sensor" || t.kind == "weather") {
    if (t.show_title)
      title_label(LV_ALIGN_TOP_LEFT, pad, pad, inner_w - (with_icon ? 34 : 0));
    if (with_icon || t.kind == "weather") {
      view.icon = make_label(o, icon_font(t.kind == "weather" && big ? 40 : 28), t.icon_color, sym ? sym : "");
      lv_obj_align(view.icon, LV_ALIGN_TOP_RIGHT, -pad, pad - 4);
    }
    view.value = make_label(o, font_px(big ? 40 : (pw < 110 ? 20 : 28)), t.fg, "–");
    lv_obj_set_width(view.value, inner_w);
    lv_label_set_long_mode(view.value, LABEL_LONG_DOTS);
    lv_obj_align(view.value, LV_ALIGN_BOTTOM_LEFT, pad, t.kind == "weather" ? -(pad + 18) : -pad);
    if (t.kind == "weather") {
      view.sub = make_label(o, font_px(12), t.fg, "");
      lv_obj_set_width(view.sub, inner_w);
      lv_label_set_long_mode(view.sub, LABEL_LONG_DOTS);
      lv_obj_align(view.sub, LV_ALIGN_BOTTOM_LEFT, pad, -pad);
    }
  } else if (t.kind == "nav" || t.kind == "action" || t.kind == "settings") {
    if (with_icon) {
      view.icon = make_label(o, icon_font(big ? 40 : 28), t.icon_color, sym);
      lv_obj_align(view.icon, LV_ALIGN_CENTER, 0, t.show_title ? -14 : 0);
    }
    if (t.show_title) {
      title_label(with_icon ? LV_ALIGN_BOTTOM_MID : LV_ALIGN_CENTER, 0, with_icon ? -pad : 0, inner_w);
      lv_obj_set_style_text_align(view.title, LV_TEXT_ALIGN_CENTER, 0);
    }
  } else if (t.kind == "text") {
    view.title = make_label(o, title_font, t.fg, t.title.c_str());
    lv_obj_set_width(view.title, inner_w);
    lv_obj_set_style_text_align(view.title, LV_TEXT_ALIGN_CENTER, 0);
    lv_obj_align(view.title, LV_ALIGN_CENTER, 0, 0);
  } else if (t.kind == "status") {
    view.value = make_label(o, font_px(16), t.fg, LV_SYMBOL_WIFI " WLAN");
    lv_obj_align(view.value, LV_ALIGN_LEFT_MID, pad, -12);
    view.sub = make_label(o, font_px(16), t.fg, LV_SYMBOL_HOME " HA");
    lv_obj_align(view.sub, LV_ALIGN_LEFT_MID, pad, 14);
  } else if (t.kind == "cover" || t.kind == "thermostat" || t.kind == "media") {
    // header: icon + title, main value, secondary line, button row at the bottom
    int btn_h = ph >= 200 ? 52 : (ph >= 120 ? 40 : 32);
    int top = pad;
    if (with_icon) {
      view.icon = make_label(o, icon_font(20), t.icon_color, sym);
      lv_obj_align(view.icon, LV_ALIGN_TOP_LEFT, pad, top - 2);
    }
    if (t.show_title)
      title_label(LV_ALIGN_TOP_LEFT, pad + (with_icon ? 26 : 0), top, inner_w - (with_icon ? 26 : 0));
    bool room_for_value = ph - btn_h - 2 * pad >= 40;
    if (room_for_value) {
      bool media = t.kind == "media";
      view.value = make_label(o, font_px(media ? 16 : (big ? 40 : (ph >= 140 ? 28 : 20))), t.fg, "–");
      lv_obj_set_width(view.value, inner_w);
      lv_label_set_long_mode(view.value, LABEL_LONG_DOTS);
      lv_obj_align(view.value, LV_ALIGN_TOP_LEFT, pad, top + 24);
      if (ph - btn_h - 2 * pad >= 84 || media) {
        view.sub = make_label(o, font_px(12), t.fg, "");
        lv_obj_set_width(view.sub, inner_w);
        lv_label_set_long_mode(view.sub, LABEL_LONG_DOTS);
        lv_obj_align(view.sub, LV_ALIGN_BOTTOM_LEFT, pad, -(pad + btn_h + 6));
      }
    }
    static const uint8_t COVER[] = {BTN_UP, BTN_STOP, BTN_DOWN};
    static const uint8_t CLIMATE[] = {BTN_MINUS, BTN_PLUS};
    static const uint8_t MEDIA[] = {BTN_PREV, BTN_PLAY, BTN_NEXT};
    static const uint8_t MEDIA_FULL[] = {BTN_VOL_DOWN, BTN_PREV, BTN_PLAY, BTN_NEXT, BTN_VOL_UP};
    if (t.kind == "cover")
      this->add_buttons_(index, o, t, COVER, 3, pad, pw, btn_h);
    else if (t.kind == "thermostat")
      this->add_buttons_(index, o, t, CLIMATE, 2, pad, pw, btn_h);
    else if (pw >= 280)
      this->add_buttons_(index, o, t, MEDIA_FULL, 5, pad, pw, btn_h);
    else
      this->add_buttons_(index, o, t, MEDIA, 3, pad, pw, btn_h);
  } else if (t.kind == "graph") {
    // title + current value on top, history bars in the middle, min–max label at the bottom
    if (t.show_title)
      title_label(LV_ALIGN_TOP_LEFT, pad, pad, inner_w - 90);
    view.value = make_label(o, font_px(20), t.fg, "–");
    lv_obj_align(view.value, LV_ALIGN_TOP_RIGHT, -pad, pad - 2);
    view.sub = make_label(o, font_px(12), t.fg, "");
    lv_obj_set_width(view.sub, inner_w);
    lv_label_set_long_mode(view.sub, LABEL_LONG_DOTS);
    lv_obj_align(view.sub, LV_ALIGN_BOTTOM_LEFT, pad, -pad + 2);
    int top = pad + 28, bottom = pad + 16;
    view.graph_area = make_plain(o);
    lv_obj_set_pos(view.graph_area, pad, top);
    lv_obj_set_size(view.graph_area, inner_w, ph - top - bottom);
  } else {  // light, dimmer, rgb, switch and generic entity tiles
    bool rgb = t.kind == "rgb";
    bool dimmer = t.kind == "dimmer" || rgb;
    int slider_h = dimmer ? (ph >= 140 ? 18 : 12) : 0;
    int swatch_h = rgb ? (ph >= 140 ? 28 : 20) : 0;
    int bottom = dimmer ? pad + slider_h + 10 + (rgb ? swatch_h + 8 : 0) : pad;
    if (with_icon) {
      view.icon = make_label(o, icon_font(big ? 40 : 28), t.icon_color, sym);
      lv_obj_align(view.icon, LV_ALIGN_TOP_LEFT, pad, pad - 2);
    }
    if (t.show_state) {
      view.value = make_label(o, font_px(t.font == 0 ? 12 : 16), t.fg, "");
      lv_obj_set_width(view.value, inner_w);
      lv_label_set_long_mode(view.value, LABEL_LONG_DOTS);
      lv_obj_align(view.value, LV_ALIGN_BOTTOM_LEFT, pad, -bottom);
    }
    if (t.show_title)
      title_label(LV_ALIGN_BOTTOM_LEFT, pad, t.show_state ? -(bottom + 20) : -bottom, inner_w);
    if (dimmer) {
      lv_obj_t *s = lv_slider_create(o);
      view.slider = s;
      lv_obj_set_size(s, inner_w - 8, slider_h);
      lv_obj_align(s, LV_ALIGN_BOTTOM_MID, 0, -(pad + 2));
      lv_slider_set_range(s, 0, 100);
      lv_obj_set_style_bg_color(s, lv_color_hex(t.fg), LV_PART_MAIN);
      lv_obj_set_style_bg_opa(s, LV_OPA_20, LV_PART_MAIN);
      lv_obj_set_style_bg_color(s, lv_color_hex(t.on_bg), LV_PART_INDICATOR);
      lv_obj_set_style_bg_opa(s, LV_OPA_COVER, LV_PART_INDICATOR);
      lv_obj_set_style_bg_color(s, lv_color_hex(0xFFFFFF), LV_PART_KNOB);
      lv_obj_set_style_pad_all(s, slider_h / 4, LV_PART_KNOB);
      lv_obj_set_ext_click_area(s, 12);
      // a horizontal drag on the slider must not switch pages
      GS_REMOVE_FLAG(s, LV_OBJ_FLAG_GESTURE_BUBBLE);
      lv_obj_set_user_data(s, reinterpret_cast<void *>(static_cast<intptr_t>(index)));
      lv_obj_add_event_cb(s, slider_event_cb, LV_EVENT_ALL, this);
      if (rgb)
        this->add_swatches_(index, o, pad, pw, pad + slider_h + 10, swatch_h);
    }
  }

  this->views_.push_back(view);
  this->tile_index_[t.id] = index;
  if (!t.entity.empty())
    this->entity_views_[t.entity].push_back(index);
}

