  lv_slider_set_value(sl, view.slider != nullptr ? static_cast<int>(lv_slider_get_value(view.slider)) : level, LV_ANIM_OFF);
  lv_obj_set_style_bg_color(sl, lv_color_hex(0x1C232C), LV_PART_MAIN);
