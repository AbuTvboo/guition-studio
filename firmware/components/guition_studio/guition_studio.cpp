void GuitionStudio::setup() {
  if (!this->load_from_nvs_("layout", "crc")) {
    ESP_LOGW(TAG, "No valid active layout in flash (%s), trying previous", this->boot_error_.c_str());
    if (this->load_from_nvs_("prev", "pcrc")) {
      ESP_LOGW(TAG, "Recovered previous layout rev %d", this->layout_.revision);
    }
  }
  this->load_overrides_();
#ifdef USE_GS_SLIDESHOW
  if (this->slide_img_ != nullptr) {
    this->slide_img_->add_on_finished_callback([this](bool /*cached*/) { this->slide_ready_(); });
    this->slide_img_->add_on_error_callback([this]() { this->slide_failed_(); });
  }
#endif
  this->ui_dirty_ = true;
}

void GuitionStudio::dump_config() {
  ESP_LOGCONFIG(TAG, "Guition Studio:");
  ESP_LOGCONFIG(TAG, "  Hardware: %s", this->hardware_.c_str());
  ESP_LOGCONFIG(TAG, "  Firmware: %s, protocol %d", ESPHOME_PROJECT_VERSION, PROTOCOL_VERSION);
  ESP_LOGCONFIG(TAG, "  Max layout size: %u bytes", (unsigned) this->max_layout_size_);
  ESP_LOGCONFIG(TAG, "  Layout: %s (rev %d, crc %08x)", this->has_layout_ ? "loaded" : "default",
                this->layout_.revision, (unsigned) this->layout_crc_);
}

void GuitionStudio::loop() {
  uint32_t now = millis();
  if (this->ui_dirty_) {
    this->ui_dirty_ = false;
    if (this->has_layout_) {
      this->build_ui_();
    } else {
      this->build_default_ui_();
    }
    this->hide_screensaver_();
    this->close_settings_();
    this->close_color_picker_();
    this->apply_rotation_();
    this->apply_touch_mode_();
    this->set_backlight_(this->dimmed_ ? std::min(this->standby_(), this->effective_brightness_())
                                       : this->effective_brightness_());
  }

  if (this->hold_active_)
    this->hold_update_(now);

  if (now - this->last_heartbeat_ >= 300000u) {  // every 5 minutes: lets HA track uptime/heap and detect reboots
    this->last_heartbeat_ = now;
    char payload[96];
    snprintf(payload, sizeof(payload), "{\"up\":%u,\"heap\":%u,\"psram\":%u}", (unsigned) (now / 1000),
             (unsigned) heap_caps_get_free_size(MALLOC_CAP_INTERNAL), (unsigned) heap_caps_get_free_size(MALLOC_CAP_SPIRAM));
    this->emit("hb", payload);
  }

  if (now - this->last_tick_ >= 1000) {
    this->last_tick_ = now;
    this->update_status_();
    this->refresh_settings_();
    if (this->ss_obj_ != nullptr && this->ss_img_ != nullptr && !this->slide_pending_ && now >= this->slide_next_at_)
      this->slide_next_();
    if (this->ss_obj_ != nullptr && this->layout_.mix && now >= this->ss_switch_at_) {
      // mix: prayer times <-> football
      this->ss_view_ = 1 - this->ss_view_;
      this->ss_switch_at_ = now + static_cast<uint32_t>(this->layout_.mix_interval) * 1000u;
      this->build_ss_content_();
      this->update_status_();
    } else if (this->fb_list_ != nullptr && this->fb_dirty_) {
      this->fb_dirty_ = false;
      int page = this->fb_page_;
      uint32_t page_at = this->fb_page_at_;
      this->render_football_();
      this->fb_page_ = page < this->fb_pages_ ? page : 0;
      this->fb_page_at_ = page_at;  // logos must not reset the page timer
    } else if (this->fb_list_ != nullptr && this->fb_pages_ > 1 && now >= this->fb_page_at_) {
      this->fb_page_ = (this->fb_page_ + 1) % this->fb_pages_;
      this->render_football_();
      this->update_status_();
    }
    if (this->ss_obj_ == nullptr && !this->slide_pending_ && this->slide_buf_[0] != nullptr)
      this->slide_stop_();
    if (this->ota_obj_ != nullptr && this->ota_hide_at_ != 0 && now > this->ota_hide_at_) {
      GS_OBJ_DELETE(this->ota_obj_);
      this->ota_obj_ = this->ota_fill_ = this->ota_title_ = this->ota_sub_ = this->ota_pct_ = nullptr;
      this->ota_hide_at_ = 0;
    }
    if (this->notify_obj_ != nullptr && this->notify_until_ != 0 && now > this->notify_until_)
      this->close_notification_();
  }

  if (now - this->last_idle_check_ >= 250) {
    this->last_idle_check_ = now;
    uint32_t inactive = GS_INACTIVE_MS();
    const auto &l = this->layout_;
    if (this->timeout_() > 0 && !this->dimmed_ && inactive > static_cast<uint32_t>(this->timeout_()) * 1000u) {
      this->dimmed_ = true;
      this->set_backlight_(std::min(this->standby_(), this->effective_brightness_()));
    } else if (this->dimmed_ && inactive < 400) {
      this->wake_();
    }
    if (this->screensaver_s_() > 0 && this->has_layout_ && this->ss_obj_ == nullptr && this->menu_obj_ == nullptr &&
        inactive > static_cast<uint32_t>(this->screensaver_s_()) * 1000u) {
      this->show_screensaver_();
    } else if (this->ss_obj_ != nullptr && inactive < 400) {
      this->hide_screensaver_();
    }
    if (l.home_after_s > 0 && !this->returned_home_ && inactive > static_cast<uint32_t>(l.home_after_s) * 1000u) {
      this->returned_home_ = true;
      if (this->current_page_ != l.home)
        this->show_page_(l.home, false);
    } else if (inactive < 400) {
      this->returned_home_ = false;
    }
  }
}

