void GuitionStudio::update_screensaver_(const std::string &hhmm, const std::string &date) {
  if (this->ss_obj_ == nullptr)
    return;
  lv_label_set_text(this->ss_clock_, hhmm.c_str());
  lv_label_set_text(this->ss_date_, date.c_str());
  const auto &l = this->layout_;
  for (int i = 0; i < 2; i++) {
    if (this->ss_lines_[i] == nullptr)
      continue;
    auto it = this->states_.find(l.ss_entities[i]);
    std::string value = (it != this->states_.end() && it->second.known)
                            ? (it->second.available ? it->second.display : l.txt_unavailable)
                            : std::string("…");
    std::string title = i < static_cast<int>(l.ss_titles.size()) ? l.ss_titles[i] : "";
    std::string text = title.empty() ? value : title + "  " + value;
    lv_label_set_text(this->ss_lines_[i], text.c_str());
  }
}

