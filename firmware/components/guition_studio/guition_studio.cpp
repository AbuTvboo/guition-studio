void GuitionStudio::set_football(const std::string &json) {
  JsonDocument doc(&psram_allocator);
  if (deserializeJson(doc, json)) {
    ESP_LOGW(TAG, "Invalid football payload");
    return;
  }
  this->fb_header_ = std::string(doc["h"] | "").substr(0, 48);
  this->fb_groups_.clear();
  size_t total = 0;
  for (JsonArrayConst g : doc["g"].as<JsonArrayConst>()) {
    FootballGroup group;
    group.name = std::string(g[0] | "").substr(0, 32);
    for (JsonArrayConst r : g[1].as<JsonArrayConst>()) {
      if (++total > 60)
        break;
      group.rows.push_back({std::string(r[0] | "").substr(0, 12), std::string(r[1] | "").substr(0, 24),
                            std::string(r[2] | "").substr(0, 24), std::string(r[4] | "").substr(0, 8),
                            static_cast<uint8_t>(clampi(r[3] | 0, 0, 3)), std::string(r[5] | "").substr(0, 12),
                            std::string(r[6] | "").substr(0, 12)});
    }
    group.color = parse_color(g[2], group.color);
    if (!group.rows.empty())
      this->fb_groups_.push_back(std::move(group));
  }
  JsonArrayConst texts = doc["t"].as<JsonArrayConst>();
  if (texts.size() >= 3) {
    this->fb_title_ = std::string(texts[0] | "").substr(0, 24);
    this->fb_end_ = std::string(texts[1] | "").substr(0, 16);
    this->fb_off_ = std::string(texts[2] | "").substr(0, 16);
  }
  if (this->fb_list_ != nullptr)
    this->render_football_();
}

void GuitionStudio::set_logo(const std::string &key, const std::string &data) {
  const size_t bytes = LOGO_PX * LOGO_PX * 3;  // RGB565 plane + alpha plane
  if (key.empty() || key.size() > 12 || this->logos_.count(key) || this->logos_.size() >= 120)
    return;
  auto *buf = static_cast<uint8_t *>(heap_caps_malloc(bytes, MALLOC_CAP_SPIRAM));
  if (buf == nullptr)
    return;
  if (base64_decode(data, buf, bytes) != bytes) {
    heap_caps_free(buf);
    ESP_LOGW(TAG, "Invalid logo %s", key.c_str());
    return;
  }
  TeamLogo &logo = this->logos_[key];
  logo.data = buf;
#if LVGL_VERSION_MAJOR >= 9
  logo.dsc.header.magic = LV_IMAGE_HEADER_MAGIC;
  logo.dsc.header.cf = LV_COLOR_FORMAT_RGB565A8;
  logo.dsc.header.stride = LOGO_PX * 2;
#else
  logo.dsc.header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA;
#endif
  logo.dsc.header.w = LOGO_PX;
  logo.dsc.header.h = LOGO_PX;
  logo.dsc.data_size = bytes;
  logo.dsc.data = buf;
  this->fb_dirty_ = true;
}

static lv_color_t darker(uint32_t rgb, int pct) {
  uint32_t r = ((rgb >> 16) & 0xFF) * pct / 100, g = ((rgb >> 8) & 0xFF) * pct / 100, b = (rgb & 0xFF) * pct / 100;
  return lv_color_hex((r << 16) | (g << 8) | b);
}

static lv_color_t lighter(uint32_t rgb, int pct) {
  uint32_t r = (rgb >> 16) & 0xFF, g = (rgb >> 8) & 0xFF, b = rgb & 0xFF;
  r += (255 - r) * pct / 100;
  g += (255 - g) * pct / 100;
  b += (255 - b) * pct / 100;
  return lv_color_hex((r << 16) | (g << 8) | b);
}

/// 3D look: light from above (vertical gradient + bright top edge) and a drop shadow below.
static void raise_obj(lv_obj_t *o, lv_color_t top, lv_color_t bottom, lv_color_t edge, int shadow, int shadow_y) {
  lv_obj_set_style_bg_color(o, top, 0);
  lv_obj_set_style_bg_grad_color(o, bottom, 0);
  lv_obj_set_style_bg_grad_dir(o, LV_GRAD_DIR_VER, 0);
  lv_obj_set_style_bg_opa(o, LV_OPA_COVER, 0);
  lv_obj_set_style_border_width(o, 1, 0);
  lv_obj_set_style_border_side(o, LV_BORDER_SIDE_TOP, 0);
  lv_obj_set_style_border_color(o, edge, 0);
  if (shadow > 0) {
    lv_obj_set_style_shadow_width(o, shadow, 0);
    lv_obj_set_style_shadow_offset_y(o, shadow_y, 0);
    lv_obj_set_style_shadow_color(o, lv_color_hex(0x000000), 0);
    lv_obj_set_style_shadow_opa(o, LV_OPA_70, 0);
  }
}

/// Glass reflection on the upper half (create before the content so it stays behind it).
