void GuitionStudio::update_graph_(TileView &view, const EntityState *st) {
  if (view.graph_area == nullptr || st == nullptr || st->graph.empty())
    return;
  const TileCfg &t = *view.cfg;
  int n = static_cast<int>(st->graph.size());
  int w = lv_obj_get_width(view.graph_area);
  int h = lv_obj_get_height(view.graph_area);
  if (w <= 0 || h <= 0) {  // layout not computed yet: use the size we set
    lv_obj_update_layout(view.graph_area);
    w = lv_obj_get_width(view.graph_area);
    h = lv_obj_get_height(view.graph_area);
  }
  if (static_cast<int>(view.bars.size()) != n) {
    for (auto *b : view.bars)
      GS_OBJ_DELETE(b);
    view.bars.clear();
    for (int i = 0; i < n; i++) {
      lv_obj_t *b = make_plain(view.graph_area);
      lv_obj_set_style_bg_opa(b, LV_OPA_COVER, 0);
      lv_obj_set_style_radius(b, 2, 0);
      view.bars.push_back(b);
    }
  }
  int gap = n > 32 ? 1 : 2;
  int bw = (w - (n - 1) * gap) / n;
  if (bw < 1)
    bw = 1;
  for (int i = 0; i < n; i++) {
    lv_obj_t *b = view.bars[i];
    int v = st->graph[i];
    if (v < 0) {
      lv_obj_add_flag(b, LV_OBJ_FLAG_HIDDEN);
      continue;
    }
    GS_REMOVE_FLAG(b, LV_OBJ_FLAG_HIDDEN);
    int bh = 2 + (h - 2) * v / 100;
    lv_obj_set_size(b, bw, bh);
    lv_obj_set_pos(b, i * (bw + gap), h - bh);
    // older values are drawn more transparent, the newest bars in the accent colour
    lv_obj_set_style_bg_color(b, lv_color_hex(t.icon_color), 0);
    lv_obj_set_style_bg_opa(b, static_cast<lv_opa_t>(LV_OPA_30 + (LV_OPA_COVER - LV_OPA_30) * i / (n > 1 ? n - 1 : 1)), 0);
  }
  if (view.sub != nullptr)
    lv_label_set_text(view.sub, st->graph_range.c_str());
}

void GuitionStudio::update_tile_(TileView &view) {
  const TileCfg &t = *view.cfg;
  if (t.kind == "clock" || t.kind == "text" || t.kind == "nav" || t.kind == "status" || t.kind == "settings")
    return;  // updated by update_status_ or static
  if (t.entity.empty())
    return;
  auto it = this->states_.find(t.entity);
  bool known = it != this->states_.end() && it->second.known;
  bool available = known && it->second.available;
  bool on = available && it->second.on;
  bool stateful = t.kind == "light" || t.kind == "switch" || t.kind == "dimmer" || t.kind == "rgb";
  const EntityState *st = known ? &it->second : nullptr;

  uint32_t bg = (on && stateful) ? t.on_bg : t.bg;
  uint32_t fg = (on && stateful) ? t.on_fg : t.fg;
  lv_obj_set_style_bg_color(view.obj, lv_color_hex(bg), 0);
  if (view.title != nullptr)
    lv_obj_set_style_text_color(view.title, lv_color_hex(fg), 0);
  if (view.value != nullptr)
    lv_obj_set_style_text_color(view.value, lv_color_hex(fg), 0);
  if (view.sub != nullptr)
    lv_obj_set_style_text_color(view.sub, lv_color_hex(fg), 0);
  if (view.icon != nullptr) {
    uint32_t ic = !available ? this->layout_.muted : (on && stateful) ? fg : (on && t.kind != "sensor" ? t.on_bg : t.icon_color);
    lv_obj_set_style_text_color(view.icon, lv_color_hex(ic), 0);
    const char *sym = (st && !st->icon.empty()) ? icon_symbol(st->icon) : nullptr;
    if (sym == nullptr)
      sym = icon_symbol(t.icon);
    lv_label_set_text(view.icon, !known || available ? (sym ? sym : "") : icon_symbol("alert"));
  }

  const char *main_text = !known ? "…" : (!available ? this->layout_.txt_unavailable.c_str() : st->display.c_str());
  if (t.kind == "media" && available && !st->sub.empty()) {
    // media: track title as main line, player state below
    if (view.value != nullptr)
      lv_label_set_text(view.value, st->sub.c_str());
    if (view.sub != nullptr)
      lv_label_set_text(view.sub, st->display.c_str());
  } else {
    if (view.value != nullptr)
      lv_label_set_text(view.value, main_text);
    if (view.sub != nullptr)
      lv_label_set_text(view.sub, available && st != nullptr ? st->sub.c_str() : "");
  }
  if (t.kind == "graph") {
    if (view.sub != nullptr)
      lv_label_set_text(view.sub, available && st != nullptr ? st->graph_range.c_str() : "");
    if (available)
      this->update_graph_(view, st);
  }
  if (view.slider != nullptr && !view.dragging) {
    int n = (st && st->num >= 0) ? st->num : (on ? 100 : 0);
    lv_slider_set_value(view.slider, on ? n : 0, LV_ANIM_OFF);
    if (available)
      lv_obj_add_flag(view.slider, LV_OBJ_FLAG_CLICKABLE);
    else
      GS_REMOVE_FLAG(view.slider, LV_OBJ_FLAG_CLICKABLE);
  }
  lv_obj_set_style_opa(view.obj, static_cast<lv_opa_t>((available || !known ? t.opacity : t.opacity / 2) * 255 / 100), 0);
}

void GuitionStudio::update_status_() {
  bool wifi_ok = false, ha_ok = false;
#ifdef USE_WIFI
  wifi_ok = wifi::global_wifi_component != nullptr && wifi::global_wifi_component->is_connected();
#endif
#ifdef USE_API
  ha_ok = api::global_api_server != nullptr && api::global_api_server->is_connected();
#endif
  uint32_t okc = this->layout_.ok_color, errc = this->layout_.err_color;
  if (this->header_wifi_ != nullptr)
    lv_obj_set_style_text_color(this->header_wifi_, lv_color_hex(wifi_ok ? okc : errc), 0);
  if (this->header_ha_ != nullptr)
    lv_obj_set_style_text_color(this->header_ha_, lv_color_hex(ha_ok ? okc : errc), 0);

  std::string hhmm = "--:--", date;
#ifdef USE_TIME
  if (this->time_ != nullptr) {
    auto now = this->time_->now();
    if (now.is_valid()) {
      hhmm = now.strftime("%H:%M");
      date = now.strftime("%d.%m.%Y");
    }
  }
#endif
  if (this->header_clock_ != nullptr)
    lv_label_set_text(this->header_clock_, hhmm.c_str());
  this->update_screensaver_(hhmm, date);

  for (auto &view : this->views_) {
    const TileCfg &t = *view.cfg;
    if (t.kind == "clock") {
      lv_label_set_text(view.value, hhmm.c_str());
      if (view.sub != nullptr)
        lv_label_set_text(view.sub, t.title.empty() ? date.c_str() : t.title.c_str());
    } else if (t.kind == "status") {
      lv_label_set_text(view.value, wifi_ok ? LV_SYMBOL_WIFI " WLAN verbunden" : LV_SYMBOL_WIFI " WLAN getrennt");
      lv_obj_set_style_text_color(view.value, lv_color_hex(wifi_ok ? okc : errc), 0);
      lv_label_set_text(view.sub, ha_ok ? LV_SYMBOL_HOME " HA verbunden" : LV_SYMBOL_HOME " HA getrennt");
      lv_obj_set_style_text_color(view.sub, lv_color_hex(ha_ok ? okc : errc), 0);
    }
  }
}

void GuitionStudio::show_page(int32_t index) {
  // Page requests from Home Assistant (rules, automations) wake the display.
  GS_TRIGGER_ACTIVITY();
  this->hide_screensaver_();
  if (this->dimmed_)
    this->wake_();
  this->show_page_(index, true);
}

void GuitionStudio::show_page_(int index, bool remember) {
  int count = static_cast<int>(this->page_objs_.size());
  if (count == 0 || index < 0 || index >= count)
    return;
  if (index == this->current_page_)
    return;
  if (remember && this->current_page_ >= 0) {
    this->history_.push_back(this->current_page_);
    if (this->history_.size() > 16)
      this->history_.erase(this->history_.begin());
  }
  for (int i = 0; i < count; i++) {
    if (i == index)
      GS_REMOVE_FLAG(this->page_objs_[i], LV_OBJ_FLAG_HIDDEN);
    else
      lv_obj_add_flag(this->page_objs_[i], LV_OBJ_FLAG_HIDDEN);
  }
  for (int i = 0; i < static_cast<int>(this->dot_objs_.size()); i++) {
    lv_obj_set_style_bg_color(this->dot_objs_[i],
                              lv_color_hex(i == index ? this->layout_.accent : this->layout_.muted), 0);
  }
  this->current_page_ = index;
  if (this->header_title_ != nullptr)
    lv_label_set_text(this->header_title_, this->layout_.pages[index].name.c_str());
  char payload[64];
  snprintf(payload, sizeof(payload), "{\"page\":%d,\"id\":\"%s\"}", index, this->layout_.pages[index].id.c_str());
  this->emit("page", payload);
}

void GuitionStudio::handle_gesture_() {
  if (!this->layout_.swipe || this->page_objs_.empty())
    return;
  lv_indev_t *indev = GS_INDEV_ACTIVE();
  if (indev == nullptr)
    return;
  lv_dir_t dir = lv_indev_get_gesture_dir(indev);
  int count = static_cast<int>(this->page_objs_.size());
  if (dir == LV_DIR_LEFT && this->current_page_ + 1 < count)
    this->show_page_(this->current_page_ + 1, true);
  else if (dir == LV_DIR_RIGHT && this->current_page_ > 0)
    this->show_page_(this->current_page_ - 1, true);
}

void GuitionStudio::on_root_event(lv_event_code_t code) {
  if (code == LV_EVENT_PRESSED) {
    if (!this->begin_press_())
      this->hold_begin_();
  } else if (code == LV_EVENT_RELEASED || code == LV_EVENT_PRESS_LOST) {
    this->hold_cancel_();
  } else if (code == LV_EVENT_GESTURE) {
    this->hold_cancel_();
    if (!this->gesture_ && !this->swallow_) {
      this->gesture_ = true;
      this->handle_gesture_();
    }
  }
}

void GuitionStudio::on_tile_event(int index, lv_event_code_t code) {
  if (index < 0 || index >= static_cast<int>(this->views_.size()))
    return;
  TileView &view = this->views_[index];
  const TileCfg &t = *view.cfg;
  switch (code) {
    case LV_EVENT_PRESSED:
      if (!this->begin_press_())
        lv_obj_set_style_opa(view.obj, static_cast<lv_opa_t>(t.opacity * 255 / 100 * 7 / 10), 0);
      break;
    case LV_EVENT_RELEASED:
    case LV_EVENT_PRESS_LOST:
      this->update_tile_(view);
      if (t.entity.empty())
        lv_obj_set_style_opa(view.obj, static_cast<lv_opa_t>(t.opacity * 255 / 100), 0);
      break;
    case LV_EVENT_GESTURE:
      if (!this->gesture_ && !this->swallow_) {
        this->gesture_ = true;
        this->handle_gesture_();
      }
      break;
    case LV_EVENT_SHORT_CLICKED:
      if (!this->swallow_ && !this->gesture_)
        this->do_action_(view, t.tap, t.tap_page, false);
      break;
    case LV_EVENT_LONG_PRESSED:
      if (!this->swallow_ && !this->gesture_)
        this->do_action_(view, t.hold, t.hold_page, true);
      break;
    default:
      break;
  }
}

/// Common start of every touch: resets gesture tracking and swallows the touch that wakes the display.
/// Returns true if the touch is swallowed.
bool GuitionStudio::begin_press_() {
  this->gesture_ = false;
  this->swallow_ = this->dimmed_;
  if (this->dimmed_)
    this->wake_();
  return this->swallow_;
}

void GuitionStudio::on_button_event(int index, uint8_t button, lv_event_code_t code) {
  if (index < 0 || index >= static_cast<int>(this->views_.size()))
    return;
  TileView &view = this->views_[index];
  switch (code) {
    case LV_EVENT_PRESSED:
      this->begin_press_();
      break;
    case LV_EVENT_GESTURE:
      if (!this->gesture_ && !this->swallow_) {
        this->gesture_ = true;
        this->handle_gesture_();
      }
      break;
    case LV_EVENT_SHORT_CLICKED:
      if (!this->swallow_ && !this->gesture_) {
        char payload[112];
        snprintf(payload, sizeof(payload), "{\"t\":\"%s\",\"p\":\"%s\",\"b\":\"%s\"}", view.cfg->id.c_str(),
                 this->layout_.pages[view.page].id.c_str(), button_name(button));
        this->emit("btn", payload);
      }
      break;
    default:
      break;
  }
}

void GuitionStudio::on_slider_event(int index, lv_event_code_t code) {
  if (index < 0 || index >= static_cast<int>(this->views_.size()))
    return;
  TileView &view = this->views_[index];
  if (view.slider == nullptr)
    return;
  switch (code) {
    case LV_EVENT_PRESSED:
      this->begin_press_();
      view.dragging = true;
      break;
    case LV_EVENT_VALUE_CHANGED:
      if (view.value != nullptr && !this->swallow_) {
        char text[16];
        snprintf(text, sizeof(text), "%d %%", static_cast<int>(lv_slider_get_value(view.slider)));
        lv_label_set_text(view.value, text);
      }
      break;
    case LV_EVENT_RELEASED:
    case LV_EVENT_PRESS_LOST: {
      view.dragging = false;
      if (this->swallow_) {
        this->update_tile_(view);  // restore the real value
        break;
      }
      char payload[112];
      snprintf(payload, sizeof(payload), "{\"t\":\"%s\",\"p\":\"%s\",\"v\":%d}", view.cfg->id.c_str(),
               this->layout_.pages[view.page].id.c_str(), static_cast<int>(lv_slider_get_value(view.slider)));
      this->emit("set", payload);
      break;
    }
    default:
      break;
  }
}

void GuitionStudio::do_action_(TileView &view, uint8_t action, int page, bool hold) {
  const TileCfg &t = *view.cfg;
  int count = static_cast<int>(this->page_objs_.size());
  switch (action) {
    case ACTION_REMOTE: {
      char payload[96];
      snprintf(payload, sizeof(payload), "{\"t\":\"%s\",\"p\":\"%s\"}", t.id.c_str(),
               this->layout_.pages[view.page].id.c_str());
      this->emit(hold ? "hold" : "tap", payload);
      break;
    }
    case ACTION_NAVIGATE:
      this->show_page_(page, true);
      break;
    case ACTION_HOME:
      this->show_page_(this->layout_.home, true);
      break;
    case ACTION_BACK:
      if (!this->history_.empty()) {
        int target = this->history_.back();
        this->history_.pop_back();
        this->show_page_(target, false);
      }
      break;
    case ACTION_NEXT:
      this->show_page_((this->current_page_ + 1) % count, true);
      break;
    case ACTION_PREV:
      this->show_page_((this->current_page_ + count - 1) % count, true);
      break;
    case ACTION_SETTINGS:
      this->open_settings_();
      break;
    case ACTION_COLOR:
      this->open_color_picker_(static_cast<int>(&view - this->views_.data()));
      break;
    default:
      break;
  }
}

void GuitionStudio::set_backlight_(int percent) {
#ifdef USE_LIGHT
  if (this->backlight_ == nullptr)
    return;
  auto call = percent > 0 ? this->backlight_->turn_on() : this->backlight_->turn_off();
  if (percent > 0)
    call.set_brightness(static_cast<float>(percent) / 100.0f);
  call.set_transition_length(300);
  call.perform();
#endif
}

void GuitionStudio::wake_() {
  this->dimmed_ = false;
  this->set_backlight_(this->effective_brightness_());
}

int GuitionStudio::effective_brightness_() const {
  return this->night_ ? std::min(this->night_brightness_, this->brightness_()) : this->brightness_();
}

void GuitionStudio::set_mode(int32_t night, int32_t brightness, int32_t dim) {
  this->night_ = night != 0;
  this->night_brightness_ = clampi(brightness, 1, 100);
  this->night_dim_ = this->night_ ? clampi(dim, 0, 80) : 0;
  this->apply_night_overlay_();
  this->set_backlight_(this->dimmed_ ? std::min(this->standby_(), this->effective_brightness_())
                                     : this->effective_brightness_());
  ESP_LOGI(TAG, "Night mode %s (brightness %d%%, dim %d%%)", this->night_ ? "on" : "off", this->night_brightness_,
           this->night_dim_);
}

void GuitionStudio::apply_night_overlay_() {
  if (this->night_dim_ <= 0) {
    if (this->night_obj_ != nullptr) {
      GS_OBJ_DELETE(this->night_obj_);
      this->night_obj_ = nullptr;
    }
    return;
  }
  if (this->night_obj_ == nullptr) {
    // non-clickable black film on the top layer: reduces glare beyond the backlight minimum
    this->night_obj_ = make_plain(lv_layer_top());
    lv_obj_set_size(this->night_obj_, SCREEN_W, SCREEN_H);
    lv_obj_set_style_bg_color(this->night_obj_, lv_color_hex(0x000000), 0);
    lv_obj_move_background(this->night_obj_);
  }
  lv_obj_set_style_bg_opa(this->night_obj_, static_cast<lv_opa_t>(this->night_dim_ * 255 / 100), 0);
}

void GuitionStudio::show_screensaver_() {
  if (this->ss_obj_ != nullptr)
    return;
  const auto &l = this->layout_;
  lv_obj_t *o = make_plain(lv_layer_top());
  this->ss_obj_ = o;
  lv_obj_set_size(o, SCREEN_W, SCREEN_H);
  lv_obj_set_style_bg_color(o, lv_color_hex(0x000000), 0);
  lv_obj_set_style_bg_opa(o, LV_OPA_COVER, 0);
  lv_obj_add_flag(o, LV_OBJ_FLAG_CLICKABLE);  // swallows the waking tap
  bool slides = false;
#ifdef USE_GS_SLIDESHOW
  slides = l.slideshow && this->slide_img_ != nullptr;
#endif
  if (slides) {
    this->ss_img_ = lv_image_create(o);
    lv_obj_set_pos(this->ss_img_, 0, 0);
    lv_obj_set_size(this->ss_img_, SCREEN_W, SCREEN_H);
    lv_obj_add_flag(this->ss_img_, LV_OBJ_FLAG_HIDDEN);  // until the first picture is decoded
    this->slide_errors_ = 0;
    this->slide_next_at_ = 0;  // load immediately
  }
  this->ss_clock_ = make_label(o, font_px(40), 0xFFFFFF, "--:--");
  lv_obj_align(this->ss_clock_, LV_ALIGN_CENTER, 0, -70);
  this->ss_date_ = make_label(o, font_px(20), l.muted, "");
  lv_obj_align(this->ss_date_, LV_ALIGN_CENTER, 0, 10);
  if (slides) {
    // small clock with a dark pill in the lower left corner over the pictures
    lv_obj_align(this->ss_clock_, LV_ALIGN_BOTTOM_LEFT, 20, -44);
    lv_obj_align(this->ss_date_, LV_ALIGN_BOTTOM_LEFT, 22, -18);
    lv_obj_set_style_text_color(this->ss_date_, lv_color_hex(0xFFFFFF), 0);
    for (lv_obj_t *lbl : {this->ss_clock_, this->ss_date_}) {
      lv_obj_set_style_bg_color(lbl, lv_color_hex(0x000000), 0);
      lv_obj_set_style_bg_opa(lbl, LV_OPA_40, 0);
      lv_obj_set_style_pad_hor(lbl, 8, 0);
      lv_obj_set_style_radius(lbl, 8, 0);
      if (!l.slide_clock)
        lv_obj_add_flag(lbl, LV_OBJ_FLAG_HIDDEN);
    }
  }
  for (int i = 0; i < 2; i++) {
    this->ss_lines_[i] = nullptr;
    if (i < static_cast<int>(l.ss_entities.size()) && !slides) {
      this->ss_lines_[i] = make_label(o, font_px(28), 0xE6EDF3, "");
      lv_obj_set_width(this->ss_lines_[i], 440);
      lv_obj_set_style_text_align(this->ss_lines_[i], LV_TEXT_ALIGN_CENTER, 0);
      lv_obj_align(this->ss_lines_[i], LV_ALIGN_CENTER, 0, 70 + i * 44);
    }
  }
  if (this->night_obj_ != nullptr)
    lv_obj_move_foreground(this->night_obj_);
  if (this->notify_obj_ != nullptr)
    lv_obj_move_foreground(this->notify_obj_);
  this->update_status_();
}

