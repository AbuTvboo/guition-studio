bool GuitionStudio::load_from_nvs_(const char *key, const char *crc_key) {
  nvs_handle_t h;
  if (nvs_open(NVS_NS, NVS_READONLY, &h) != ESP_OK) {
    this->boot_error_ = "no namespace";
    return false;
  }
  size_t size = 0;
  uint32_t stored_crc = 0;
  bool ok = false;
  if (nvs_get_blob(h, key, nullptr, &size) == ESP_OK && size > 0 && size <= this->max_layout_size_ &&
      nvs_get_u32(h, crc_key, &stored_crc) == ESP_OK) {
    char *buf = alloc_buffer(size + 1);
    if (buf != nullptr && nvs_get_blob(h, key, buf, &size) == ESP_OK) {
      buf[size] = '\0';
      uint32_t crc = crc32(reinterpret_cast<const uint8_t *>(buf), size);
      if (crc != stored_crc) {
        this->boot_error_ = "crc mismatch";
      } else {
        LayoutCfg parsed;
        std::string err;
        if (this->parse_layout_(buf, size, parsed, err)) {
          this->layout_ = std::move(parsed);
          this->layout_crc_ = crc;
          this->has_layout_ = true;
          ok = true;
        } else {
          this->boot_error_ = err;
        }
      }
    }
    free(buf);
  } else {
    this->boot_error_ = "empty";
  }
  nvs_close(h);
  return ok;
}

bool GuitionStudio::save_to_nvs_(const char *data, size_t len, uint32_t crc) {
  nvs_handle_t h;
  if (nvs_open(NVS_NS, NVS_READWRITE, &h) != ESP_OK)
    return false;
  // Keep the currently active layout as "prev" for rollback / recovery.
  size_t old_size = 0;
  uint32_t old_crc = 0;
  if (nvs_get_blob(h, "layout", nullptr, &old_size) == ESP_OK && old_size > 0 &&
      nvs_get_u32(h, "crc", &old_crc) == ESP_OK) {
    char *old = alloc_buffer(old_size);
    if (old != nullptr && nvs_get_blob(h, "layout", old, &old_size) == ESP_OK) {
      nvs_set_blob(h, "prev", old, old_size);
      nvs_set_u32(h, "pcrc", old_crc);
    }
    free(old);
  }
  // NVS replaces an entry only after the new one is fully written, so a power
  // loss keeps either the old or the new blob. The CRC check on boot catches a
  // blob/crc mismatch and falls back to "prev".
  esp_err_t err = nvs_set_blob(h, "layout", data, len);
  if (err == ESP_OK)
    err = nvs_set_u32(h, "crc", crc);
  if (err == ESP_OK)
    err = nvs_commit(h);
  nvs_close(h);
  if (err != ESP_OK)
    ESP_LOGE(TAG, "NVS write failed: %s", esp_err_to_name(err));
  return err == ESP_OK;
}

void GuitionStudio::rollback() {
  LayoutCfg backup = this->layout_;
  uint32_t backup_crc = this->layout_crc_;
  bool backup_has = this->has_layout_;
  nvs_handle_t h;
  if (nvs_open(NVS_NS, NVS_READWRITE, &h) != ESP_OK) {
    this->emit("rollback", "{\"ok\":false,\"err\":\"nvs\"}");
    return;
  }
  size_t size = 0;
  uint32_t pcrc = 0;
  bool ok = false;
  if (nvs_get_blob(h, "prev", nullptr, &size) == ESP_OK && nvs_get_u32(h, "pcrc", &pcrc) == ESP_OK) {
    char *buf = alloc_buffer(size + 1);
    if (buf != nullptr && nvs_get_blob(h, "prev", buf, &size) == ESP_OK) {
      buf[size] = '\0';
      LayoutCfg parsed;
      std::string err;
      if (crc32(reinterpret_cast<uint8_t *>(buf), size) == pcrc && this->parse_layout_(buf, size, parsed, err)) {
        nvs_close(h);
        h = 0;
        if (this->save_to_nvs_(buf, size, pcrc)) {
          this->layout_ = std::move(parsed);
          this->layout_crc_ = pcrc;
          this->has_layout_ = true;
          ok = true;
        }
      }
    }
    free(buf);
  }
  if (h != 0)
    nvs_close(h);
  if (!ok) {
    this->layout_ = std::move(backup);
    this->layout_crc_ = backup_crc;
    this->has_layout_ = backup_has;
  }
  this->ui_dirty_ = true;
  char payload[96];
  snprintf(payload, sizeof(payload), "{\"ok\":%s,\"rev\":%d,\"crc\":%u}", ok ? "true" : "false",
           this->layout_.revision, (unsigned) this->layout_crc_);
  this->emit("rollback", payload);
}

