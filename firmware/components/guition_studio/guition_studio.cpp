// ---------------------------------------------------------------- states

void GuitionStudio::set_states(const std::string &json) {
  JsonDocument doc(&psram_allocator);
  if (deserializeJson(doc, json)) {
    ESP_LOGW(TAG, "Invalid state payload");
    return;
  }
  std::vector<int> touched;
  for (JsonPairConst kv : doc["e"].as<JsonObjectConst>()) {
    std::string eid = kv.key().c_str();
    auto &st = this->states_[eid];
    JsonObjectConst v = kv.value();
    st.on = (v["o"] | 0) != 0;
    st.available = (v["a"] | 1) != 0;
    st.display = std::string(v["d"] | "").substr(0, 48);
    st.sub = std::string(v["s"] | "").substr(0, 64);
    st.icon = std::string(v["i"] | "").substr(0, 32);
    st.num = clampi(v["n"] | -1, -1, 100);
    if (v["g"].is<JsonArrayConst>()) {  // graph history only arrives with history pushes
      st.graph.clear();
      for (JsonVariantConst p : v["g"].as<JsonArrayConst>()) {
        if (st.graph.size() >= 96)
          break;
        st.graph.push_back(static_cast<int8_t>(clampi(p | -1, -1, 100)));
      }
      st.graph_range = std::string(v["gr"] | "").substr(0, 40);
    }
    st.known = true;
    auto it = this->entity_views_.find(eid);
    if (it != this->entity_views_.end())
      touched.insert(touched.end(), it->second.begin(), it->second.end());
  }
  for (JsonPairConst kv : doc["v"].as<JsonObjectConst>()) {
    auto it = this->tile_index_.find(kv.key().c_str());
    if (it == this->tile_index_.end())
      continue;
    auto &view = this->views_[it->second];
    view.visible = kv.value().as<int>() != 0;
    if (view.visible)
      GS_REMOVE_FLAG(view.obj, LV_OBJ_FLAG_HIDDEN);
    else
      lv_obj_add_flag(view.obj, LV_OBJ_FLAG_HIDDEN);
  }
  for (int idx : touched)
    this->update_tile_(this->views_[idx]);
}

