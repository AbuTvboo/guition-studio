uint32_t crc32(const uint8_t *data, size_t len) {
  // Standard CRC-32 (IEEE 802.3, identical to Python zlib.crc32)
  uint32_t crc = 0xFFFFFFFFu;
  for (size_t i = 0; i < len; i++) {
    crc ^= data[i];
    for (int b = 0; b < 8; b++)
      crc = (crc >> 1) ^ (0xEDB88320u & (0u - (crc & 1u)));
  }
  return ~crc;
}

struct PsramJsonAllocator : ArduinoJson::Allocator {
  void *allocate(size_t size) override {
    void *p = heap_caps_malloc(size, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    return p != nullptr ? p : malloc(size);
  }
  void deallocate(void *ptr) override { free(ptr); }
  void *reallocate(void *ptr, size_t size) override {
    void *p = heap_caps_realloc(ptr, size, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    return p != nullptr ? p : realloc(ptr, size);
  }
};
static PsramJsonAllocator psram_allocator;  // NOLINT

static char *alloc_buffer(size_t size) {
  auto *p = static_cast<char *>(heap_caps_malloc(size, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT));
  if (p == nullptr)
    p = static_cast<char *>(malloc(size));
  return p;
}

static uint32_t parse_color(JsonVariantConst v, uint32_t def) {
  const char *s = v | static_cast<const char *>(nullptr);
  if (s == nullptr || strlen(s) != 6)
    return def;
  char *end = nullptr;
  uint32_t c = strtoul(s, &end, 16);
  if (end == nullptr || *end != '\0')
    return def;
  return c;
}

static bool valid_id(const char *s) {
  if (s == nullptr || *s == '\0' || strlen(s) > 24)
    return false;
  for (const char *p = s; *p; p++) {
    char c = *p;
    if (!((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_' || c == '-'))
      return false;
  }
  return true;
}

static int clampi(int v, int lo, int hi) { return v < lo ? lo : (v > hi ? hi : v); }

