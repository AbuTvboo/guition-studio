  // brightness
  int by = wy + 72;
  lv_obj_t *bl = make_label(o, font_px(16), 0x8B98A5, "Helligkeit");
  lv_obj_set_pos(bl, 20, by);
  lv_obj_t *sl = lv_slider_create(o);
