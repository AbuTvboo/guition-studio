bool GuitionStudio::parse_layout_(const char *data, size_t len, LayoutCfg &out, std::string &err) {
  JsonDocument doc(&psram_allocator);
  DeserializationError de = deserializeJson(doc, data, len);
  if (de) {
    err = std::string("json:") + de.c_str();
    return false;
  }
  if ((doc["v"] | 0) != PROTOCOL_VERSION) {
    err = "version";
    return false;
  }
  out.revision = doc["rev"] | 0;
  JsonObjectConst set = doc["set"];
  out.brightness = clampi(set["br"] | 80, 5, 100);
  out.standby = clampi(set["sb"] | 10, 0, 100);
  out.timeout_s = clampi(set["to"] | 60, 0, 86400);
  out.home_after_s = clampi(set["ret"] | 0, 0, 86400);
  out.header = (set["hdr"] | 1) != 0;
  out.dots = (set["dots"] | 1) != 0;
  out.swipe = (set["swp"] | 1) != 0;
  out.header_bg = parse_color(set["hbg"], out.header_bg);
  out.header_fg = parse_color(set["hfg"], out.header_fg);
  out.muted = parse_color(set["mut"], out.muted);
  out.accent = parse_color(set["acc"], out.accent);
  out.ok_color = parse_color(set["ok"], out.ok_color);
  out.err_color = parse_color(set["err"], out.err_color);
  const char *na = set["na"] | "Nicht verfügbar";
  out.txt_unavailable = std::string(na).substr(0, 32);
  out.screensaver_s = clampi(set["ss"] | 0, 0, 86400);
  out.night_brightness = clampi(set["nb"] | 15, 1, 100);
  {
    int rot = set["rot"] | 0;
    out.rotation = (rot == 90 || rot == 180 || rot == 270) ? rot : 0;
  }
  out.touch_mode = clampi(set["tch"] | 0, 0, 3);
  out.night_dim = clampi(set["nd"] | 30, 0, 80);
  out.theme = std::string(set["th"] | "").substr(0, 24);
  out.slideshow = (set["ssm"] | 0) == 1;
  out.slide_url = std::string(set["slu"] | "").substr(0, 240);
  if (out.slide_url.rfind("http://", 0) != 0 && out.slide_url.rfind("https://", 0) != 0)
    out.slideshow = false;
  out.slide_interval = clampi(set["sli"] | 15, 5, 600);
  out.slide_clock = (set["slc"] | 1) != 0;
  out.themes.clear();
  for (JsonArrayConst t : set["thl"].as<JsonArrayConst>()) {
    if (out.themes.size() >= 8)
      break;
    out.themes.emplace_back(std::string(t[0] | "").substr(0, 24), std::string(t[1] | "").substr(0, 24));
  }
  out.ss_entities.clear();
  out.ss_titles.clear();
  for (JsonVariantConst e : set["sse"].as<JsonArrayConst>()) {
    if (out.ss_entities.size() >= 2)
      break;
    out.ss_entities.push_back(std::string(e | "").substr(0, 96));
  }
  for (JsonVariantConst t : set["sst"].as<JsonArrayConst>()) {
    if (out.ss_titles.size() >= 2)
      break;
    out.ss_titles.push_back(std::string(t | "").substr(0, 32));
  }

  JsonArrayConst pages = doc["pages"];
  if (pages.isNull() || pages.size() == 0 || pages.size() > MAX_PAGES) {
    err = "schema:pages";
    return false;
  }
  int total_tiles = 0;
  out.pages.clear();
  for (JsonObjectConst p : pages) {
    PageCfg page;
    const char *pid = p["id"] | "";
    if (!valid_id(pid)) {
      err = "schema:page_id";
      return false;
    }
    page.id = pid;
    page.name = std::string(p["n"] | "").substr(0, 32);
    page.bg = parse_color(p["bg"], page.bg);
    page.cols = p["c"] | 3;
    page.rows = p["r"] | 3;
    if (page.cols < 1 || page.cols > MAX_GRID || page.rows < 1 || page.rows > MAX_GRID) {
      err = "schema:grid";
      return false;
    }
    std::vector<uint8_t> occupied(page.cols * page.rows, 0);
    for (JsonObjectConst t : p["t"].as<JsonArrayConst>()) {
      if (++total_tiles > MAX_TILES_TOTAL) {
        err = "schema:too_many_tiles";
        return false;
      }
      TileCfg tile;
      const char *tid = t["id"] | "";
      if (!valid_id(tid)) {
        err = "schema:tile_id";
        return false;
      }
      tile.id = tid;
      tile.kind = std::string(t["k"] | "text").substr(0, 12);
      tile.entity = std::string(t["e"] | "").substr(0, 96);
      tile.title = std::string(t["ti"] | "").substr(0, 64);
      tile.icon = std::string(t["ic"] | "").substr(0, 16);
      tile.fmt = std::string(t["fmt"] | "").substr(0, 16);
      tile.x = t["x"] | -1;
      tile.y = t["y"] | -1;
      tile.w = t["w"] | 1;
      tile.h = t["h"] | 1;
      if (tile.x < 0 || tile.y < 0 || tile.w < 1 || tile.h < 1 || tile.x + tile.w > page.cols ||
          tile.y + tile.h > page.rows) {
        err = "schema:bounds:" + tile.id;
        return false;
      }
      for (int yy = tile.y; yy < tile.y + tile.h; yy++) {
        for (int xx = tile.x; xx < tile.x + tile.w; xx++) {
          uint8_t &cell = occupied[yy * page.cols + xx];
          if (cell) {
            err = "schema:overlap:" + tile.id;
            return false;
          }
          cell = 1;
        }
      }
      tile.bg = parse_color(t["bg"], tile.bg);
      tile.fg = parse_color(t["fg"], tile.fg);
      tile.icon_color = parse_color(t["icc"], tile.fg);
      tile.on_bg = parse_color(t["obg"], tile.on_bg);
      tile.on_fg = parse_color(t["ofg"], tile.on_fg);
      tile.border_color = parse_color(t["bc"], tile.border_color);
      tile.font = clampi(t["fs"] | 1, 0, 4);
      tile.radius = clampi(t["rad"] | 16, 0, 60);
      tile.border = clampi(t["bw"] | 0, 0, 8);
      tile.opacity = clampi(t["op"] | 100, 10, 100);
      tile.show_title = (t["st"] | 1) != 0;
      tile.show_state = (t["sv"] | 1) != 0;
      tile.show_icon = (t["si"] | 1) != 0;
      tile.tap = clampi(t["ta"] | 0, 0, 8);
      tile.hold = clampi(t["ha"] | 0, 0, 8);
      tile.tap_page = t["tp"] | -1;
      tile.hold_page = t["hp"] | -1;
      page.tiles.push_back(std::move(tile));
    }
    out.pages.push_back(std::move(page));
  }
  // validate navigation targets after all pages are known
  int page_count = static_cast<int>(out.pages.size());
  for (auto &page : out.pages) {
    for (auto &tile : page.tiles) {
      if (tile.tap == ACTION_NAVIGATE && (tile.tap_page < 0 || tile.tap_page >= page_count))
        tile.tap = ACTION_NONE;
      if (tile.hold == ACTION_NAVIGATE && (tile.hold_page < 0 || tile.hold_page >= page_count))
        tile.hold = ACTION_NONE;
    }
  }
  out.home = clampi(set["home"] | 0, 0, page_count - 1);
  return true;
}

// ---------------------------------------------------------------- transfer

void GuitionStudio::free_rx_() {
  free(this->rx_buf_);
  this->rx_buf_ = nullptr;
  this->rx_len_ = 0;
}

void GuitionStudio::ack_(int32_t session, bool ok, const std::string &err) {
  char payload[160];
  snprintf(payload, sizeof(payload), "{\"s\":%d,\"ok\":%s,\"rev\":%d,\"crc\":%u,\"err\":\"%s\"}", (int) session,
           ok ? "true" : "false", this->layout_.revision, (unsigned) this->layout_crc_, err.c_str());
  this->emit("ack", payload);
}

void GuitionStudio::layout_begin(int32_t session, int32_t total, int32_t crc) {
  this->free_rx_();
  this->rx_session_ = session;
  this->rx_total_ = static_cast<uint32_t>(total);
  this->rx_crc_ = static_cast<uint32_t>(crc);
  this->rx_next_index_ = 0;
  this->rx_failed_ = false;
  this->rx_error_.clear();
  if (total <= 0 || static_cast<uint32_t>(total) > this->max_layout_size_) {
    this->rx_failed_ = true;
    this->rx_error_ = "size";
    return;
  }
  this->rx_buf_ = alloc_buffer(this->rx_total_ + 1);
  if (this->rx_buf_ == nullptr) {
    this->rx_failed_ = true;
    this->rx_error_ = "oom";
  }
  ESP_LOGI(TAG, "Layout transfer %d started: %d bytes", (int) session, (int) total);
}

void GuitionStudio::layout_chunk(int32_t session, int32_t index, const std::string &data) {
  if (session != this->rx_session_ || this->rx_failed_)
    return;
  if (index != this->rx_next_index_) {
    this->rx_failed_ = true;
    this->rx_error_ = "sequence";
    return;
  }
  if (this->rx_len_ + data.size() > this->rx_total_) {
    this->rx_failed_ = true;
    this->rx_error_ = "overflow";
    return;
  }
  memcpy(this->rx_buf_ + this->rx_len_, data.data(), data.size());
  this->rx_len_ += data.size();
  this->rx_next_index_++;
}

void GuitionStudio::layout_commit(int32_t session) {
  if (session != this->rx_session_) {
    this->ack_(session, false, "session");
    return;
  }
  if (this->rx_failed_) {
    std::string err = this->rx_error_;
    this->free_rx_();
    this->ack_(session, false, err);
    return;
  }
  if (this->rx_len_ != this->rx_total_) {
    this->free_rx_();
    this->ack_(session, false, "incomplete");
    return;
  }
  this->rx_buf_[this->rx_len_] = '\0';
  uint32_t crc = crc32(reinterpret_cast<const uint8_t *>(this->rx_buf_), this->rx_len_);
  if (crc != this->rx_crc_) {
    this->free_rx_();
    this->ack_(session, false, "crc");
    return;
  }
  LayoutCfg parsed;
  std::string err;
  if (!this->parse_layout_(this->rx_buf_, this->rx_len_, parsed, err)) {
    ESP_LOGW(TAG, "Rejected layout: %s", err.c_str());
    this->free_rx_();
    this->ack_(session, false, err);
    return;
  }
  // Only persist after full validation; the active layout stays untouched on failure.
  if (!this->save_to_nvs_(this->rx_buf_, this->rx_len_, crc)) {
    this->free_rx_();
    this->ack_(session, false, "nvs");
    return;
  }
  this->free_rx_();
  this->layout_ = std::move(parsed);
  this->layout_crc_ = crc;
  this->has_layout_ = true;
  this->ui_dirty_ = true;
  this->clear_overrides_();
  ESP_LOGI(TAG, "Layout rev %d applied (%u pages)", this->layout_.revision, (unsigned) this->layout_.pages.size());
  this->ack_(session, true, "");
}

