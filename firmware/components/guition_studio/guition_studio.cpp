static const lv_font_t *font_px(int px) {
  if (px >= 40)
    return &gs_font_40;
  if (px >= 28)
    return &gs_font_28;
  if (px >= 20)
    return &gs_font_20;
  if (px >= 16)
    return &gs_font_16;
  return &gs_font_12;
}

static const lv_font_t *font_step(uint8_t step) {
  static const int PX[] = {12, 16, 20, 28, 40};
  return font_px(PX[step > 4 ? 4 : step]);
}

// Material Design Icons subset, generated by scripts/gen-icons.mjs (gs_icons.h / gs_icon_font_*.c)
static const char *icon_symbol(const std::string &name) {
  if (name.empty())
    return nullptr;
  for (const auto &i : ICON_GLYPHS)
    if (name == i.name)
      return i.utf8;
  return nullptr;
}

