#!/usr/bin/env node
// Generates the text fonts of the display firmware (Montserrat Medium, SIL OFL 1.1)
// with German/Western European characters (äöüß, „“, ·, –, …, °, € …).
// LVGL's built-in Montserrat only contains ASCII, so umlauts showed as boxes.
//
// The three LVGL symbols used by the firmware (WIFI, HOME, BELL) are taken from
// Material Design Icons and placed at the LV_SYMBOL_* code points, so the
// LV_SYMBOL_* macros keep working with these fonts.
//
// Usage: node scripts/gen-fonts.mjs <Montserrat-Medium.ttf> <materialdesignicons-webfont.ttf> <lv_font_conv.js>
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const [montserrat, mdi, fontConv] = process.argv.slice(2);
if (!montserrat || !mdi || !fontConv) {
  console.error("usage: node scripts/gen-fonts.mjs <Montserrat-Medium.ttf> <materialdesignicons-webfont.ttf> <lv_font_conv.js>");
  process.exit(1);
}

const SIZES = [12, 16, 20, 28, 40];
// ASCII, Latin-1 (incl. äöüÄÖÜß, °, ·, ²³, ½), Turkish (Ğğ İı Şş), typographic quotes/dashes, bullet, ellipsis, €, arrows, minus
const TEXT_RANGE = "0x20-0x7E,0xA0-0xFF,0x11E-0x11F,0x130-0x131,0x15E-0x15F,0x2013-0x2014,0x2018-0x201E,0x2022,0x2026,0x20AC,0x2190-0x2193,0x2212";
// MDI glyph => LV_SYMBOL code point (FontAwesome positions used by LVGL)
const SYMBOLS = [
  "0xF05A9=>0xF1EB", // mdi-wifi  -> LV_SYMBOL_WIFI
  "0xF02DC=>0xF015", // mdi-home  -> LV_SYMBOL_HOME
  "0xF009A=>0xF0F3", // mdi-bell  -> LV_SYMBOL_BELL
].join(",");

const compDir = join(root, "firmware", "components", "guition_studio");
for (const size of SIZES) {
  const out = join(compDir, `gs_font_${size}.c`);
  execFileSync(
    process.execPath,
    [fontConv, "--font", montserrat, "-r", TEXT_RANGE, "--font", mdi, "-r", SYMBOLS, "--size", String(size), "--bpp", "4", "--format", "lvgl", "--no-compress", "--lv-include", "lvgl.h", "-o", out],
    { stdio: "inherit" }
  );
  let src = readFileSync(out, "utf8");
  src = src.replace(/^ \* Opts:.*$/m, ` * Opts: --size ${size} --bpp 4 --format lvgl --no-compress (Montserrat Medium, Latin-1 + Turkish + symbols)`);
  writeFileSync(out, `/* Generated by scripts/gen-fonts.mjs – Montserrat (SIL OFL 1.1) + Material Design Icons (Pictogrammers Free License) */\n${src}`);
}
console.log(`Generated text fonts in sizes ${SIZES.join(", ")}`);
