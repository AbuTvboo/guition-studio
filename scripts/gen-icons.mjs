#!/usr/bin/env node
// Generates the Material Design Icons subset used by Guition Studio:
//   firmware/components/guition_studio/gs_icon_font_<size>.c  (LVGL fonts via lv_font_conv)
//   firmware/components/guition_studio/gs_icons.h            (name -> UTF-8 table)
//   custom_components/guition_studio/icons.py                (valid names + legacy map)
//   frontend/src/icon-list.ts                                (editor list)
//
// Usage: node scripts/gen-icons.mjs <dir of @mdi/font> <path to lv_font_conv.js>
// Icons: Pictogrammers Free License (https://pictogrammers.com/docs/general/license/)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const [mdiDir, fontConv] = process.argv.slice(2);
if (!mdiDir || !fontConv) {
  console.error("usage: node scripts/gen-icons.mjs <@mdi/font dir> <lv_font_conv.js>");
  process.exit(1);
}
const cfg = JSON.parse(readFileSync(join(root, "scripts", "icons.json"), "utf8"));
const css = readFileSync(join(mdiDir, "css", "materialdesignicons.css"), "utf8");
const ttf = join(mdiDir, "fonts", "materialdesignicons-webfont.ttf");

const codepoints = {};
for (const name of cfg.icons) {
  const m = css.match(new RegExp(`\\.mdi-${name}::before\\s*\\{\\s*content:\\s*"\\\\([0-9A-Fa-f]+)"`));
  if (!m) throw new Error(`icon not found in @mdi/font: ${name}`);
  codepoints[name] = parseInt(m[1], 16);
}
for (const [legacy, target] of Object.entries(cfg.legacy)) {
  if (!(target in codepoints)) throw new Error(`legacy target missing: ${legacy} -> ${target}`);
}

const compDir = join(root, "firmware", "components", "guition_studio");
const range = Object.values(codepoints).map((c) => `0x${c.toString(16)}`).join(",");
for (const size of cfg.sizes) {
  const out = join(compDir, `gs_icon_font_${size}.c`);
  execFileSync(process.execPath, [fontConv, "--font", ttf, "-r", range, "--size", String(size), "--bpp", "4", "--format", "lvgl", "--no-compress", "--lv-include", "lvgl.h", "-o", out], { stdio: "inherit" });
  // ESPHome builds LVGL as a component: include it the simple way
  let src = readFileSync(out, "utf8");
  src = src.replace(/#ifdef LV_LVGL_H_INCLUDE_SIMPLE[\s\S]*?#endif/, "#include <lvgl.h>");
  // drop the "Opts:" line (contains local absolute paths)
  src = src.replace(/^ \* Opts:.*$/m, ` * Opts: --size ${size} --bpp 4 --format lvgl --no-compress (${Object.keys(codepoints).length} glyphs)`);
  writeFileSync(out, `/* Generated by scripts/gen-icons.mjs – Material Design Icons (Pictogrammers Free License) */\n${src}`);
}

const utf8 = (cp) => Array.from(Buffer.from(String.fromCodePoint(cp), "utf8"), (b) => `\\x${b.toString(16).toUpperCase()}`).join("");
const entries = cfg.icons.map((n) => `    {"${n}", "${utf8(codepoints[n])}"},`).join("\n");
writeFileSync(
  join(compDir, "gs_icons.h"),
  `// Generated by scripts/gen-icons.mjs – do not edit.
#pragma once
#include <lvgl.h>

extern "C" {
${cfg.sizes.map((s) => `extern const lv_font_t gs_icon_font_${s};`).join("\n")}
}

namespace esphome {
namespace guition_studio {

struct IconGlyph {
  const char *name;
  const char *utf8;
};

static const IconGlyph ICON_GLYPHS[] = {
${entries}
};

}  // namespace guition_studio
}  // namespace esphome
`
);

const py = `"""Generated by scripts/gen-icons.mjs – do not edit."""

ICONS = [
${cfg.icons.map((n) => `    "${n}",`).join("\n")}
]

LEGACY_ICONS = {
${Object.entries(cfg.legacy).map(([k, v]) => `    "${k}": "${v}",`).join("\n")}
}
`;
writeFileSync(join(root, "custom_components", "guition_studio", "icons.py"), py);

const ts = `// Generated by scripts/gen-icons.mjs – do not edit.
export const DEVICE_ICONS: string[] = ${JSON.stringify(cfg.icons, null, 2)};

export const LEGACY_ICONS: Record<string, string> = ${JSON.stringify(cfg.legacy, null, 2)};
`;
writeFileSync(join(root, "frontend", "src", "icon-list.ts"), ts);
console.log(`Generated ${cfg.icons.length} icons in sizes ${cfg.sizes.join(", ")}`);

