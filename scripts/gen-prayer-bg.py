#!/usr/bin/env python3
"""Embed the prayer times backgrounds as JPEG in the firmware.

Raw RGB565 pictures cost 460 KB each (480x480x2) and made the OTA file huge.
As baseline JPEG they are ~10x smaller; the firmware decodes the selected one
into PSRAM when the screensaver opens (JPEGDEC, already used by the slideshow).

Usage: python scripts/gen-prayer-bg.py   (reads firmware/images/prayer-bg-<key>.png,
       writes firmware/components/guition_studio/gs_prayer_bg.c)
Keys/order must match PRAYER_BACKGROUNDS in custom_components/guition_studio/layout.py.
"""

from io import BytesIO
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
KEYS = ["basmala", "mosque"]
QUALITY = 90

out = [
    "/* Generated by scripts/gen-prayer-bg.py – prayer times backgrounds (480x480 baseline JPEG).",
    " * Calligraphy set in Amiri (SIL OFL 1.1), source: scripts/prayer-bg.html */",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "",
]
sizes = []
for key in KEYS:
    img = Image.open(ROOT / "firmware" / "images" / f"prayer-bg-{key}.png").convert("RGB")
    assert img.size == (480, 480), img.size
    buf = BytesIO()
    # 4:4:4 keeps the thin gold calligraphy crisp; baseline (not progressive) for JPEGDEC
    img.save(buf, "JPEG", quality=QUALITY, subsampling=0, optimize=True, progressive=False)
    data = buf.getvalue()
    sizes.append(len(data))
    out.append(f"static const uint8_t GS_BG_{key.upper()}[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ", ".join(f"0x{b:02X}" for b in data[i : i + 24]) + ",")
    out.append("};")
    out.append("")
out.append(f"const int GS_PRAYER_BG_COUNT = {len(KEYS)};")
out.append("const uint8_t *const GS_PRAYER_BG_DATA[] = {" + ", ".join(f"GS_BG_{k.upper()}" for k in KEYS) + "};")
out.append("const size_t GS_PRAYER_BG_SIZE[] = {" + ", ".join(str(s) for s in sizes) + "};")
target = ROOT / "firmware" / "components" / "guition_studio" / "gs_prayer_bg.c"
target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"{target.name}: " + ", ".join(f"{k} {s // 1024} KB" for k, s in zip(KEYS, sizes)))
